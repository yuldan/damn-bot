func docsSHA256Hex(data []byte) string {
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:])
}

func translationBanner(source, sum string) string {
	return fmt.Sprintf("<!-- translation: source=%s sha256=%s -->\n", source, sum)
}

func translationIssues(docsRoot string) []string {
	bannerRE := regexp.MustCompile(`^<!-- translation: source=(\S+) sha256=([0-9a-f]{64}) -->$`)
	localeRE := regexp.MustCompile(`^[a-z]{2}(-[A-Za-z]+)?$`)
	var issues []string
	walkErr := filepath.WalkDir(docsRoot, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, rerr := filepath.Rel(docsRoot, path)
		if rerr != nil {
			return fmt.Errorf("rel %s: %w", path, rerr)
		}
		parts := strings.Split(rel, string(filepath.Separator))
		if len(parts) != 2 || !localeRE.MatchString(parts[0]) || d.IsDir() || !strings.HasSuffix(path, ".md") {
			return nil
		}
		issues = append(issues, translationPageIssues(path, parts[0], bannerRE)...)
		return nil
	})
	if walkErr != nil {
		issues = append(issues, fmt.Sprintf("%s: walk: %v", docsRoot, walkErr))
	}
	sort.Strings(issues)
	return issues
}

func translationPageIssues(path, locale string, bannerRE *regexp.Regexp) []string {
	data, err := os.ReadFile(path) //nolint:gosec // repo fixture path
	if err != nil {
		return []string{fmt.Sprintf("%s: read: %v", path, err)}
	}
	lines := strings.SplitN(string(data), "\n", 3)
	m := bannerRE.FindStringSubmatch(strings.TrimSuffix(lines[0], "\r"))
	if m == nil {
		return []string{fmt.Sprintf("%s: missing translation source sha banner", path)}
	}
	source := filepath.Join(filepath.Dir(path), filepath.FromSlash(m[1]))
	src, err := os.ReadFile(source) //nolint:gosec // source path comes from the translation banner
	if err != nil {
		return []string{fmt.Sprintf("%s: source %s: %v", path, source, err)}
	}
	want := docsSHA256Hex([]byte(normalizeEOL(string(src))))
	if m[2] != want {
		return []string{fmt.Sprintf("%s: STALE %s sha256=%s, source is %s", path, locale, m[2], want)}
	}
	return nil
}

func checkDocLinks(root string) ([]linkIssue, int) {
	var issues []linkIssue
	external := 0
	walkErr := filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(path, ".md") {
			return err
		}
		found, skipped := fileLinkIssues(root, path)
		issues = append(issues, found...)
		external += skipped
		return nil
	})
	if walkErr != nil {
		issues = append(issues, linkIssue{File: root, Reason: walkErr.Error()})
	}
	return issues, external
}

func fileLinkIssues(root, path string) ([]linkIssue, int) {
	data, err := os.ReadFile(path) //nolint:gosec // repo fixture path
	if err != nil {
		return []linkIssue{{File: path, Reason: err.Error()}}, 0
	}
	text := stripCode(normalizeEOL(string(data)))
	rel := strings.TrimPrefix(path, root+string(filepath.Separator))
	linkRE := regexp.MustCompile(`\[[^\]]*\]\(([^)\s]+)(?:\s+"[^"]*")?\)`)
	var issues []linkIssue
	external := 0
	for _, m := range linkRE.FindAllStringSubmatchIndex(text, -1) {
		target := text[m[2]:m[3]]
		line := 1 + strings.Count(text[:m[0]], "\n")
		switch {
		case regexp.MustCompile(`^[a-z][a-z0-9+.-]*:`).MatchString(target), strings.HasPrefix(target, "//"):
			external++
			continue
		}
		if issue := resolveDocLink(path, rel, line, target); issue != nil {
			issues = append(issues, *issue)
		}
	}
	return issues, external
}

func resolveDocLink(path, rel string, line int, target string) *linkIssue {
	file, anchor, _ := strings.Cut(target, "#")
	dest := path
	if file != "" {
		dest = filepath.Join(filepath.Dir(path), filepath.FromSlash(file))
		if _, err := os.Stat(dest); err != nil { //nolint:gosec // link target comes from repo docs
			return &linkIssue{File: rel, Line: line, Target: target, Reason: "missing file"}
		}
	}
	if anchor == "" || !strings.HasSuffix(dest, ".md") {
		return nil
	}
	body, err := os.ReadFile(dest) //nolint:gosec // anchor target comes from repo docs
	if err != nil {
		return &linkIssue{File: rel, Line: line, Target: target, Reason: "unreadable anchor target"}
	}
	if !hasAnchor(string(body), anchor) {
		return &linkIssue{File: rel, Line: line, Target: target, Reason: "missing anchor"}
	}
	return nil
}

func hasAnchor(markdown, anchor string) bool {
	counts := map[string]int{}
	for line := range strings.SplitSeq(normalizeEOL(markdown), "\n") {
		if !strings.HasPrefix(line, "#") {
			continue
		}
		heading := strings.TrimSpace(strings.TrimLeft(line, "#"))
		slug := slugify(heading)
		n := counts[slug]
		counts[slug]++
		if n > 0 {
			slug = fmt.Sprintf("%s-%d", slug, n)
		}
		if slug == anchor {
			return true
		}
	}
	return false
}

func slugify(heading string) string {
	heading = strings.ToLower(heading)
	heading = strings.NewReplacer("`", "", "*", "", "_", "").Replace(heading)
	heading = regexp.MustCompile(`[^\p{L}\p{N} _-]`).ReplaceAllString(heading, "")
	return strings.ReplaceAll(strings.TrimSpace(heading), " ", "-")
}

func stripCode(text string) string {
	text = regexp.MustCompile("(?s)```.*?```").ReplaceAllString(text, "")
	return regexp.MustCompile("`[^`\\n]*`").ReplaceAllString(text, "")
}
