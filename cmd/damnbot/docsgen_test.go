func dockerEnv(t *testing.T, root string) map[string]string {
	t.Helper()
	out := map[string]string{}
	data := normalizeEOL(string(docsReadFile(t, filepath.Join(root, "Dockerfile"))))
	for _, block := range regexp.MustCompile(`(?m)^ENV\s+((?:[^\n]*\\\n)*[^\n]*)$`).FindAllStringSubmatch(data, -1) {
		fields := strings.FieldsSeq(strings.ReplaceAll(block[1], "\\\n", " "))
		for f := range fields {
			if k, v, ok := strings.Cut(f, "="); ok {
				out[k] = v
			}
		}
	}
	if len(out) == 0 {
		t.Fatal("Dockerfile: no ENV block found")
	}
	return out
}

