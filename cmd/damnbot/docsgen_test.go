// Generated references (GAP-INF-10). Every table below is produced from the
// code: the surface registry owns commands, the flag registrations and manual
// `--flag` comparisons own CLI flags, the tagged config struct owns keys and
// env names, and the Dockerfile/unit renderer own entrypoint, unit and bind.
// UPDATE_DOCS=1 rewrites the checked-in files (see the go:generate line).

const docsHeader = "<!-- Code generated by `go generate ./cmd/damnbot`; DO NOT EDIT. -->\n\n"

type flagRow struct {
	Name    string
	Where   string
	Default string
	Usage   string
}

type configRow struct {
	Type    string
	Default string
	Env     string
}

type linkIssue struct {
	File   string
	Line   int
	Target string
	Reason string
}

// TestCLIDocsMatchHelp is E-83: docs and `damnbot help` share one registry.
// It fails on a ghost flag/command (named in docs, absent from code), on a
// command whose help does not render, and on drift in the generated CLI page.
func TestCLIDocsMatchHelp(t *testing.T) {
	root := repoRoot(t)
	flags := codeFlags(t, root)
	commands := callableCommandSet()
	ghostFlags, ghostCmds := scanLivingDocs(t, root, flags, commands)
	for _, g := range ghostFlags {
		t.Errorf("%s: flag %q is documented but not registered in code", g.File, g.Target)
	}
	for _, g := range ghostCmds {
		t.Errorf("%s: command %q is documented but not callable", g.File, g.Target)
	}
	checkGenerated(t, filepath.Join(root, "docs", "reference", "CLI.md"), renderCLIReference(flags))
	for _, e := range callableSurfaces() {
		var out, errOut bytes.Buffer
		if code := surfaceHelp(&out, &errOut, []string{e.Name}); code != 0 {
			t.Errorf("damnbot help %s exited %d: %s", e.Name, code, errOut.String())
			continue
		}
		if !strings.Contains(out.String(), e.Name) {
			t.Errorf("damnbot help %s does not name the command", e.Name)
		}
	}
}

// TestConfigDocSync checks docs/CONFIG-REFERENCE.md against the tagged schema
// in both directions: every schema key is documented with its type/default/env
// and every documented key still exists (no ghost config keys).
func TestConfigDocSync(t *testing.T) {
	root := repoRoot(t)
	schema := schemaRows(t)
	docPath := filepath.Join(root, "docs", "CONFIG-REFERENCE.md")
	doc := parseConfigDoc(t, docsReadFile(t, docPath))
	for key, want := range schema {
		got, ok := doc[key]
		if !ok {
			t.Errorf("%s: schema key %s is missing from the reference", docPath, key)
			continue
		}
		if got != want {
			t.Errorf("%s: %s = %+v, schema says %+v", docPath, key, got, want)
		}
	}
	for key := range doc {
		if _, ok := schema[key]; !ok {
			t.Errorf("%s: documented key %s does not exist in the schema", docPath, key)
		}
	}
	checkGenerated(t, docPath, generateConfigText(t))
}

// TestEnvDocSync keeps the generated env page tied to the config schema (one
