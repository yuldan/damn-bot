func livingDocs(t *testing.T, root string) []string {
	t.Helper()
	var out []string
	err := filepath.WalkDir(filepath.Join(root, "docs"), func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(path, ".md") {
			return err
		}
		rel, rerr := filepath.Rel(root, path)
		if rerr != nil {
			return fmt.Errorf("rel %s: %w", path, rerr)
		}
		rel = filepath.ToSlash(rel)
		for _, skip := range livingDocsSkip() {
			ok, merr := filepath.Match(skip.glob, rel)
			if merr != nil {
				t.Fatalf("skip glob %q: %v", skip.glob, merr)
			}
			if ok {
				return nil
			}
		}
		out = append(out, path)
		return nil
	})
	if err != nil {
		t.Fatalf("walk docs: %v", err)
	}
	sort.Strings(out)
	return out
}

func scanLivingDocs(t *testing.T, root string, flags []flagRow, commands map[string]bool) ([]linkIssue, []linkIssue) {
	t.Helper()
	known := map[string]bool{}
	for _, f := range flags {
		known[f.Name] = true
	}
	var ghostFlags, ghostCmds []linkIssue
	for _, path := range livingDocs(t, root) {
		rel := strings.TrimPrefix(path, root+string(filepath.Separator))
		for _, line := range documentLines(t, path) {
			if !strings.HasPrefix(line.Text, "damnbot ") {
				continue
			}
			for _, name := range flagsInCommand(line.Text) {
				if !known[name] {
					ghostFlags = append(ghostFlags, linkIssue{File: rel, Line: line.Number, Target: name})
				}
			}
			cmd := strings.Trim(strings.Fields(line.Text)[1], "[]()<>`")
			if !skipCommandToken(cmd) && !commands[cmd] {
				ghostCmds = append(ghostCmds, linkIssue{File: rel, Line: line.Number, Target: cmd})
			}
		}
	}
	return ghostFlags, ghostCmds
}

type numberedLine struct {
	Number int
	Text   string
}

// documentLines returns inline code spans and fenced-block lines that start a
// damnbot invocation. Markdown prose that merely names a flag is not a claim
// about the CLI.
func documentLines(t *testing.T, path string) []numberedLine {
	t.Helper()
	data := docsReadFile(t, path)
	var out []numberedLine
	inFence := false
	for i, raw := range strings.Split(normalizeEOL(string(data)), "\n") {
		line := strings.TrimSpace(raw)
		if strings.HasPrefix(line, "```") {
			inFence = !inFence
			continue
		}
		candidates := []string{}
		if inFence {
			candidates = append(candidates, strings.TrimSpace(strings.TrimPrefix(strings.TrimPrefix(line, "$"), "#")))
		} else {
			for _, m := range regexp.MustCompile("`([^`]*)`").FindAllStringSubmatch(line, -1) {
				candidates = append(candidates, strings.TrimSpace(m[1]))
			}
		}
		for _, c := range candidates {
			c = shellPart(c)
			if strings.HasPrefix(c, "damnbot ") {
				out = append(out, numberedLine{Number: i + 1, Text: c})
			}
		}
	}
	return out
}

// skipCommandToken ignores placeholders (`<cmd>`, `[flags]`), flags, version
// strings, and hidden `__` helpers that are implementation details, not
// documented surfaces.
func skipCommandToken(cmd string) bool {
	if cmd == "" || strings.Contains(cmd, "…") {
		return true
	}
	if strings.HasPrefix(cmd, "<") || strings.HasPrefix(cmd, "[") || strings.HasPrefix(cmd, "-") || strings.HasPrefix(cmd, "__") {
		return true
	}
	return cmd[0] >= '0' && cmd[0] <= '9'
}

// shellPart drops a trailing shell comment (`# journalctl --user -u …`) so
// flags of another tool are not attributed to damnbot.
func shellPart(s string) string {
	for _, marker := range []string{" # ", "\t# "} {
		if i := strings.Index(s, marker); i >= 0 {
			s = s[:i]
		}
	}
	return strings.TrimSpace(s)
}

func flagsInCommand(s string) []string {
	re := regexp.MustCompile(`(?:^|[\s([=])--?([a-z][a-z0-9-]*)`)
	var out []string
	for _, m := range re.FindAllStringSubmatch(s, -1) {
		out = append(out, m[1])
	}
	return out
}

func renderCLIReference(flags []flagRow) string {
	var b strings.Builder
	b.WriteString(docsHeader)
	b.WriteString("# CLI reference\n\n")
	b.WriteString("Commands, flags and defaults generated from `cmd/damnbot` (surface registry and flag sets). ")
	b.WriteString("`godoc`-style prose is hand-written; this table is not.\n\n## Commands\n\n| Command | Summary |\n|---|---|\n")
	entries := append(callableSurfaces(), surfaceEntry{Name: "help", Summary: "Offline help topics and guides"})
	sort.Slice(entries, func(i, j int) bool { return entries[i].Name < entries[j].Name })
	for _, e := range entries {
		fmt.Fprintf(&b, "| `damnbot %s` | %s |\n", e.Name, e.Summary)
	}
	b.WriteString("\n## Flags\n\n| Flag | Registered in | Default | Usage |\n|---|---|---|---|\n")
	for _, f := range flags {
		fmt.Fprintf(&b, "| `--%s` | `%s` | `%s` | %s |\n", f.Name, f.Where, f.Default, escapeCell(f.Usage))
	}
	return b.String()
}

func escapeCell(s string) string {
	s = strings.ReplaceAll(s, "|", `\|`)
	return strings.ReplaceAll(s, "\n", " ")
}

func schemaRows(t *testing.T) map[string]configRow {
	t.Helper()
	base := config.Default()
	v := reflect.ValueOf(base)
	typ := v.Type()
	out := map[string]configRow{}
	for i := range typ.NumField() {
		sectionField := typ.Field(i)
		section := tomlTagOf(&sectionField)
		if section == "" || v.Field(i).Kind() != reflect.Struct {
			continue
		}
		fv, ft := v.Field(i), v.Field(i).Type()
		for j := range ft.NumField() {
			f := ft.Field(j)
			key := tomlTagOf(&f)
			field := fv.Field(j)
			if key == "" || !field.CanInterface() || !scalarKind(field.Kind()) && field.Type() != reflect.TypeFor[config.Duration]() {
				continue
			}
			out[section+"."+key] = configRow{
				Type:    field.Type().String(),
				Default: defaultText(field),
				Env:     config.EnvName(section, key),
			}
		}
	}
	return out
}

func parseConfigDoc(t *testing.T, data []byte) map[string]configRow {
	t.Helper()
	rowRE := regexp.MustCompile("^\\| `([a-z0-9_.]+)` \\| ([^|]+) \\| `([^`]*)` \\| `([A-Z0-9_]+)` \\|$")
	out := map[string]configRow{}
	for line := range strings.SplitSeq(normalizeEOL(string(data)), "\n") {
		m := rowRE.FindStringSubmatch(strings.TrimSpace(line))
		if m == nil {
			continue
		}
		out[m[1]] = configRow{Type: strings.TrimSpace(m[2]), Default: m[3], Env: m[4]}
	}
	return out
}

