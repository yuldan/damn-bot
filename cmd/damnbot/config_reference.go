package main

import (
	"bytes"
	"flag"
	"fmt"
	"io"
	"os"
	"reflect"
	"strings"

	"github.com/BurntSushi/toml"
	"github.com/damnbot/damnbot/internal/config"
)

// generateConfigReference renders the example config, key table and env
// reference from the tagged Go struct (GAP-OPS-01). docs/CONFIG-REFERENCE.md
// is this output; the drift test regenerates it.
func generateConfigReference() (string, error) {
	base := config.Default()
	base.ConfigVersion = config.SchemaVersion
	var b strings.Builder
	b.WriteString("# Config reference\n\n")
	b.WriteString("<!-- Code generated by `go generate ./internal/config`; DO NOT EDIT. -->\n\n")
	b.WriteString("## Example config\n\n```toml\n")
	var enc bytes.Buffer
	if err := toml.NewEncoder(&enc).Encode(base); err != nil {
		return "", fmt.Errorf("encode example: %w", err)
	}
	b.Write(enc.Bytes())
	b.WriteString("```\n\n## Keys\n\n| Key | Type | Default | Env |\n|---|---|---|---|\n")
	v := reflect.ValueOf(base)
	t := v.Type()
	for i := range t.NumField() {
		sf := t.Field(i)
		section := tomlTagOf(&sf)
		if section == "" || v.Field(i).Kind() != reflect.Struct {
			continue
		}
		fv, ft := v.Field(i), v.Field(i).Type()
		for j := range ft.NumField() {
			keyField := ft.Field(j)
			key := tomlTagOf(&keyField)
			if key == "" {
				continue
			}
			field := fv.Field(j)
			if !field.CanInterface() || !scalarKind(field.Kind()) && field.Type() != reflect.TypeFor[config.Duration]() {
				continue
			}
			fmt.Fprintf(&b, "| `%s.%s` | %s | `%s` | `%s` |\n",
				section, key, field.Type(), defaultText(field), config.EnvName(section, key))
		}
	}
	return b.String(), nil
}

func tomlTagOf(f *reflect.StructField) string {
	tag, _, _ := strings.Cut(f.Tag.Get("toml"), ",")
	if tag == "-" {
		return ""
	}
	return tag
}

func scalarKind(k reflect.Kind) bool {
	return k == reflect.String || k == reflect.Bool || k >= reflect.Int && k <= reflect.Int64 ||
		k >= reflect.Float32 && k <= reflect.Float64
}

func defaultText(v reflect.Value) string {
	if v.Type() == reflect.TypeFor[config.Duration]() {
		return config.Duration(v.Int()).String()
	}
	return fmt.Sprint(v.Interface())
}

func configReferenceCmd(args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("config reference", flag.ContinueOnError)
	fs.SetOutput(stderr)
	out := fs.String("o", "", "write to file instead of stdout")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	text, err := generateConfigReference()
	if err != nil {
		return configFail(stderr, "config reference", err)
	}
	if *out == "" {
		return say(stdout, "%s", text)
	}
	if err := os.WriteFile(*out, []byte(text), 0o600); err != nil {
		return configFail(stderr, "config reference", err)
	}
	return say(stdout, "wrote %s\n", *out)
}
