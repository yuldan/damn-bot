package budget

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/damnbot/damnbot/bench/budget/o200k"
)

var updateCalibration = flag.Bool("update-calibration", false, "rewrite internal/budget/testdata/calibration/o200k.tsv")

// calibrationDir holds the TestTokenEstimatorCalibration corpus of the main
// module (internal/budget, ADR-067/ADR-101); the tokenizer lives only here.
const calibrationDir = "../../internal/budget/testdata/calibration"

// TestCalibrationCorpusCounts: o200k.tsv (lang, paragraph, o200k_base token
// count) matches the corpus, so the runtime estimator test in the main
// module compares against real tokenizer counts without importing it.
func TestCalibrationCorpusCounts(t *testing.T) {
	tok, err := o200k.Load()
	if err != nil {
		t.Fatal(err)
	}
	var b strings.Builder
	b.WriteString("# lang\tparagraph\to200k_base tokens — generated by bench/budget TestCalibrationCorpusCounts -update-calibration\n")
	for _, lang := range []string{"en", "id", "ru", "ja"} {
		src, err := os.ReadFile(filepath.Join(calibrationDir, lang+".txt"))
		if err != nil {
			t.Fatal(err)
		}
		for i, p := range strings.Split(strings.TrimSpace(string(src)), "\n\n") {
			fmt.Fprintf(&b, "%s\t%d\t%d\n", lang, i, tok.Count(p))
		}
	}
	path := filepath.Join(calibrationDir, "o200k.tsv")
	if *updateCalibration {
		if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(path)
	if err != nil || string(got) != b.String() {
		t.Fatalf("%s out of date (%v); run: cd bench && go test ./budget -run TestCalibrationCorpusCounts -update-calibration\nwant:\n%s", path, err, b.String())
	}
}
